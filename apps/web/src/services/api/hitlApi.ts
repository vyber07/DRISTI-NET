import { get, post, type ApiResponse } from "./real_client";

import type { HITLTask, HITLFilter, HITLTaskDecision, HITLProposedMatch, MatchedEntitySummary, HITLTaskStatus, HITLTaskType, HITLTaskPriority } from "@/types/hitl";

const DECISION_ACTION: Record<string, HITLTaskDecision["action"]> = { APPROVE: "APPROVE_MERGE", REJECT: "REJECT_MERGE", DEFER: "DEFER" };

function mapCandidateToTask(cand: any): HITLTask {
  const reviews: any[] = Array.isArray(cand.reviews) ? cand.reviews : [];
  const last = reviews.length ? reviews[reviews.length - 1] : null;
  let statusStr = cand.state;
  if (statusStr === "REVIEW_REQUIRED") statusStr = "PENDING";
  else if (statusStr === "APPROVE") statusStr = "APPROVED";
  else if (statusStr === "REJECT") statusStr = "REJECTED";
  else if (statusStr === "DEFER" || statusStr === "ESCALATE") statusStr = "ESCALATED";
  
  return {
    id: cand.candidate_id,
    caseId: cand.case_id,
    caseTitle: "Case " + cand.case_id,
    type: "ENTITY_MERGE" as HITLTaskType,
    priority: "HIGH" as HITLTaskPriority,
    status: statusStr as HITLTaskStatus,
    title: `Candidate Match: ${cand.left?.label || 'Unknown'} <-> ${cand.right?.label || 'Unknown'}`,
    description: `Automated match generated by ${cand.matcher_version || 'system'}.`,
    confidence: cand.confidence || 0,
    flagManualReview: cand.state === "REVIEW_REQUIRED",
    entityAId: cand.left?.entity_id || "",
    entityAName: cand.left?.label || "Unknown",
    entityBId: cand.right?.entity_id || "",
    entityBName: cand.right?.label || "Unknown",
    evidenceIds: cand.evidence_ids || [],
    primaryEvidenceId: cand.evidence_ids?.[0] || "",
    hasContradiction: cand.conflicts && cand.conflicts.length > 0,
    proposedMatch: {
      entityA: { id: cand.left?.entity_id || "", name: cand.left?.label || "", type: cand.left?.kind || "", attributes: cand.left?.attributes || {} },
      entityB: { id: cand.right?.entity_id || "", name: cand.right?.label || "", type: cand.right?.kind || "", attributes: cand.right?.attributes || {} },
      similarityScore: cand.confidence || 0,
      similarityMetrics: [],
      candidateReason: ""
    },
    // DEF-059: the matcher's reasons, counter-evidence, conflicts and missingness were never shown to the reviewer.
    signals: {
      positive: Array.isArray(cand.positive_signals) ? cand.positive_signals : [],
      counter: Array.isArray(cand.counter_evidence) ? cand.counter_evidence : [],
      conflicts: Array.isArray(cand.conflicts) ? cand.conflicts : [],
      missing: Array.isArray(cand.missing) ? cand.missing : [],
    },
    // DEF-060: resolved tasks rendered a blank decision because `decision` was never mapped from reviews[].
    decision: last ? {
      action: DECISION_ACTION[last.decision] || ("DEFER" as HITLTaskDecision["action"]),
      officerName: last.reviewer_id || "",
      officerBadge: last.decision,
      justification: last.reason || "",
      arbitratedAt: last.created_at || "",
    } : undefined,
    assignedAnalyst: cand.assigned_to ? { name: cand.assigned_to, badge: "" } : undefined,
    createdAt: cand.created_at || new Date().toISOString(),
    updatedAt: cand.created_at || new Date().toISOString(),
    slaDeadline: new Date(Date.now() + 86400000).toISOString()
  };
}

export async function listHITLTasks(filter?: HITLFilter): Promise<ApiResponse<HITLTask[]>> {
  const caseId = filter?.caseId || "";
  if (!caseId) throw new Error("caseId required");
  const data = await get(`/cases/${caseId}/candidates`);
  // DEF-097: status and search filters were sent nowhere and applied nowhere; apply them to the API result.
  const q = (filter?.searchQuery || "").trim().toLowerCase();
  const tasks = (Array.isArray(data) ? data.map(mapCandidateToTask) : []).filter((t) =>
    (!filter?.status || filter.status === "ALL" || t.status === filter.status) &&
    (!q || [t.id, t.entityAName, t.entityBName || "", t.title].some((v) => v.toLowerCase().includes(q))));
  return { data: tasks, meta: { requestId: "req", timestamp: new Date().toISOString(), durationMs: 0, securityClassification: "REAL" } };
}
export async function getHITLTask(taskId: string): Promise<ApiResponse<HITLTask>> {
  const data = await get(`/candidates/${taskId}`);
  return { data: mapCandidateToTask(data), meta: { requestId: "req", timestamp: new Date().toISOString(), durationMs: 0, securityClassification: "REAL" } };
}
export async function submitTaskDecision(taskId: string, decision: HITLTaskDecision): Promise<ApiResponse<HITLTask>> {
  const data = await post(`/candidates/${taskId}/decision`, {
    decision: decision.action === "APPROVE_MERGE" ? "APPROVE" : (decision.action === "REJECT_MERGE" ? "REJECT" : "DEFER"),
    reason: decision.justification
  });
  return { data: mapCandidateToTask(data), meta: { requestId: "req", timestamp: new Date().toISOString(), durationMs: 0, securityClassification: "REAL" } };
}

export async function getHITLStats(caseId?: string): Promise<ApiResponse<any>> {
  if (!caseId) throw new Error("caseId required");
  const data = await get(`/cases/${caseId}/stats`);
  return { data, meta: { requestId: "req", timestamp: new Date().toISOString(), durationMs: 0, securityClassification: "REAL" } };
}

export async function assignTask(taskId: string, analyst: any): Promise<ApiResponse<any>> {
  const data = await post(`/candidates/${taskId}/assign`, { analyst });
  return { data: mapCandidateToTask(data), meta: { requestId: "req", timestamp: new Date().toISOString(), durationMs: 0, securityClassification: "REAL" } };
}
