"""Measure the pinned NER model on data/evaluation/ner_synthetic_v1.json and write reports/ner-evaluation.md.

Runs the real model through the same adapter the pipeline uses (services/nlp_adapter.extract_entities), offline
(DRISHTI_NER_OFFLINE=1: the pinned revision must be in the local Hugging Face cache). Two scores per type:
  exact   -- same type and identical character span
  overlap -- same type and the spans overlap (separates boundary errors from misses)
No numbers are invented: if the model cannot be loaded the script exits non-zero and writes nothing.

Run: python3 -m scripts.evaluate_ner
"""
from __future__ import annotations

import json
import os
import platform
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

os.environ.setdefault("DRISHTI_NER_OFFLINE", "1")
REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
DATA = REPO / "data" / "evaluation" / "ner_synthetic_v1.json"
OUT = REPO / "reports" / "ner-evaluation.md"
TYPES = ("PERSON", "ORGANIZATION", "LOCATION")


def prf(tp: int, fp: int, fn: int) -> tuple[float, float, float]:
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    return p, r, (2 * p * r / (p + r) if p + r else 0.0)


def main() -> int:
    from apps.api.app.services import nlp_adapter
    try:
        nlp_adapter._get_pipeline()
    except Exception as exc:
        print(f"cannot load the pinned NER model ({type(exc).__name__}: {exc}); nothing written", file=sys.stderr)
        return 1
    data = json.loads(DATA.read_text())
    exact = {t: Counter() for t in TYPES}
    overlap = {t: Counter() for t in TYPES}
    misses, false_pos, boundary = [], [], []
    for s in data["sentences"]:
        gold = [(e["type"], e["start"], e["end"]) for e in s["entities"]]
        preds = []
        for c in nlp_adapter.extract_entities(s["text"], evidence_id=s["id"], page=1, line_start=1):
            start = c.locator.get("char_offset", 0)
            preds.append((c.kind, start, start + len(c.original_text)))
        for t in TYPES:
            g = {x for x in gold if x[0] == t}
            p = {x for x in preds if x[0] == t}
            tp = len(g & p)
            exact[t].update(tp=tp, fp=len(p - g), fn=len(g - p))
            # overlap: greedy one-to-one matching of same-type overlapping spans
            used, otp = set(), 0
            for gg in sorted(g):
                hit = next((pp for pp in sorted(p) if pp not in used and pp[1] < gg[2] and gg[1] < pp[2]), None)
                if hit:
                    used.add(hit)
                    otp += 1
                    if hit != gg:
                        boundary.append((s["id"], t, s["text"][gg[1]:gg[2]], s["text"][hit[1]:hit[2]]))
                else:
                    misses.append((s["id"], t, s["text"][gg[1]:gg[2]], s["text"]))
            for pp in sorted(p - used):
                false_pos.append((s["id"], t, s["text"][pp[1]:pp[2]], s["text"]))
            overlap[t].update(tp=otp, fp=len(p) - otp, fn=len(g) - otp)

    def table(scores):
        rows = ["| type | gold | predicted | correct | precision | recall | F1 |", "|---|---|---|---|---|---|---|"]
        tot = Counter()
        for t in TYPES:
            c = scores[t]
            tot.update(c)
            p, r, f = prf(c["tp"], c["fp"], c["fn"])
            rows.append(f"| {t} | {c['tp'] + c['fn']} | {c['tp'] + c['fp']} | {c['tp']} | {p:.3f} | {r:.3f} | {f:.3f} |")
        p, r, f = prf(tot["tp"], tot["fp"], tot["fn"])
        rows.append(f"| **all (micro)** | {tot['tp'] + tot['fn']} | {tot['tp'] + tot['fp']} | {tot['tp']} | {p:.3f} | {r:.3f} | {f:.3f} |")
        return rows

    n_gold = sum(len(s["entities"]) for s in data["sentences"])
    lines = [
        "# NER evaluation (synthetic, template-based)",
        "",
        f"Computed {datetime.now(timezone.utc).isoformat(timespec='seconds')} by `scripts/evaluate_ner.py`.",
        "",
        "## Conditions",
        f"- Model: `{nlp_adapter._MODEL_NAME}` at pinned revision `{nlp_adapter._MODEL_REVISION}` (offline, local cache), "
        "through `services/nlp_adapter.extract_entities` — the same code path the pipeline uses.",
        f"- Dataset: `data/evaluation/ner_synthetic_v1.json` (seed {data['seed']}): {len(data['sentences'])} sentences, "
        f"{n_gold} gold entities, generated by `scripts/make_ner_eval_set.py` from 10 FIR-style templates with fictional "
        "people and organisations and common Indian place names.",
        f"- Host: {platform.platform()}, Python {platform.python_version()}.",
        "- **Scope limitation:** synthetic, template-based English sentences. These numbers describe behaviour on text "
        "like the demo data. They are not a real-world accuracy figure and must not be quoted as one. Every model output "
        "remains a REVIEW_REQUIRED candidate.",
        "",
        "## Exact match (same type, identical span)",
        *table(exact),
        "",
        "## Overlap match (same type, spans overlap — isolates boundary errors)",
        *table(overlap),
        "",
        f"## Error examples ({len(misses)} misses, {len(false_pos)} false positives, {len(boundary)} boundary differences)",
        "",
        "Misses (gold entity not found):",
        *[f"- {sid} {t}: `{txt}` — “{sent}”" for sid, t, txt, sent in misses[:12]],
        "",
        "False positives (predicted, not in gold):",
        *[f"- {sid} {t}: `{txt}` — “{sent}”" for sid, t, txt, sent in false_pos[:12]],
        "",
        "Errors by template (sentence S<n> uses template (n-1) mod 10 in `scripts/make_ner_eval_set.py`):",
        *[f"- template {k}: {v} error(s)" for k, v in sorted(Counter((int(sid[1:]) - 1) % 10 for sid, *_ in misses + false_pos).items())],
        "",
        "Interpretation: read the examples before quoting any number. A cluster in one template usually means an "
        "annotation choice (e.g. whether \"<city> police station\" is a location or an organisation), not a general weakness; "
        "a probe outside this set has also shown missed person names at the start of a sentence (DEF-018).",
        "",
        "Boundary differences (gold → predicted):",
        *[f"- {sid} {t}: `{g}` → `{p}`" for sid, t, g, p in boundary[:12]],
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("\n".join(table(exact) + [""] + table(overlap)))
    print(f"misses={len(misses)} false_positives={len(false_pos)} boundary={len(boundary)}; wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
